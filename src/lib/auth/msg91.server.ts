/**
 * Server-only MSG91 delivery for Better Auth's generated phone OTP.
 *
 * Better Auth generates and verifies the code. MSG91 is used only to deliver
 * that same code through a pre-approved Flow/DLT template; this avoids a
 * second OTP authority or split verification state.
 */
export type Msg91Settings = {
  authKey: string;
  templateId: string;
  otpVariable?: string;
};

export type Msg91Fetch = typeof fetch;

/** Validate the exact E.164 representation required by the Indian OTP flow. */
export function isValidIndiaE164Phone(phoneNumber: string): boolean {
  return /^\+91[6-9]\d{9}$/.test(phoneNumber);
}

/** Stable placeholder email required by Better Auth for phone-only sign-up. */
export function temporaryEmailForIndiaPhone(phoneNumber: string): string {
  if (!isValidIndiaE164Phone(phoneNumber)) {
    throw new Error("Phone number must be a valid Indian E.164 mobile number.");
  }
  return `customer+${phoneNumber.replace(/\D/g, "")}@phone.fieldly.invalid`;
}

export function normalizeIndiaMobile(phoneNumber: string): string {
  const digits = phoneNumber.replace(/\D/g, "");
  const national = digits.startsWith("91") && digits.length === 12
    ? digits.slice(2)
    : digits;
  if (!/^[6-9]\d{9}$/.test(national)) {
    throw new Error("Phone number must be a valid Indian mobile number.");
  }
  return `91${national}`;
}

function parsePayload(text: string): Record<string, unknown> | null {
  if (!text.trim()) return null;
  try {
    const value: unknown = JSON.parse(text);
    return value && typeof value === "object" && !Array.isArray(value)
      ? value as Record<string, unknown>
      : null;
  } catch {
    return null;
  }
}

/**
 * Send an OTP already generated by Better Auth using MSG91's Flow API.
 * MSG91's approved transactional/DLT template must contain the configured
 * variable (VAR1 by default) in the OTP message text.
 */
export async function sendOtpWithMsg91(
  args: {
    settings: Msg91Settings;
    phoneNumber: string;
    code: string;
    fetchImpl?: Msg91Fetch;
  },
): Promise<void> {
  const { settings, phoneNumber, code } = args;
  if (!settings.authKey.trim()) throw new Error("MSG91 auth key is not configured.");
  if (!settings.templateId.trim()) throw new Error("MSG91 OTP template ID is not configured.");
  if (!/^\d{6}$/.test(code)) throw new Error("OTP code must contain exactly six digits.");

  const otpVariable = (settings.otpVariable ?? "VAR1").trim();
  if (!/^[A-Za-z][A-Za-z0-9_]{0,31}$/.test(otpVariable) || otpVariable === "mobiles") {
    throw new Error("MSG91 OTP template variable name is invalid.");
  }

  const recipient: Record<string, string> = {
    mobiles: normalizeIndiaMobile(phoneNumber),
    [otpVariable]: code,
  };
  const fetchImpl = args.fetchImpl ?? fetch;
  const response = await fetchImpl("https://control.msg91.com/api/v5/flow", {
    method: "POST",
    headers: {
      accept: "application/json",
      "content-type": "application/json",
      authkey: settings.authKey.trim(),
    },
    body: JSON.stringify({
      template_id: settings.templateId.trim(),
      short_url: "0",
      realTimeResponse: "1",
      recipients: [recipient],
    }),
    signal: AbortSignal.timeout(10_000),
  });

  const text = await response.text();
  const payload = parsePayload(text);
  const responseType = typeof payload?.type === "string"
    ? payload.type.toLowerCase()
    : null;
  if (!response.ok || responseType === "error" || responseType === "failure") {
    // Never include the auth key, OTP code or full phone number in thrown errors.
    throw new Error("MSG91 could not accept the OTP delivery request.");
  }
  if (text.trim() && !payload) {
    throw new Error("MSG91 returned an unreadable OTP delivery response.");
  }
}
